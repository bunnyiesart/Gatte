// ConnectCommand is the one line for a machine that needs no CA.
func ConnectCommand(c ConnectInfo) string {
	return fmt.Sprintf("claude mcp add --transport http --scope user --client-id '%s' --callback-port %d '%s' '%s'", c.ClientID, c.Port, c.Server, c.URL)
}

// RenderScript renders the script for one system and names its file.
func RenderScript(c ConnectInfo, system string) (string, string, error) {
	var b bytes.Buffer
	switch system {
	case adminapi.OSMacOS, adminapi.OSLinux:
		if err := shScript.Execute(&b, c); err != nil {
			return "", "", err
		}
		return b.String(), "connect-gatte.sh", nil
	case adminapi.OSWindows:
		if err := ps1Script.Execute(&b, c); err != nil {
			return "", "", err
		}
		// PowerShell 5 reads a script without a BOM as the system code
		// page; the script is ASCII, so CRLF is all it needs.
		return strings.ReplaceAll(b.String(), "\n", "\r\n"), "connect-gatte.ps1", nil
	}
	return "", "", fmt.Errorf("unknown system %q", system)
}

// Systems is the systems a connect script exists for, and how each runs
// the file it downloads.
func Systems() []adminapi.ConnectScript {
	return []adminapi.ConnectScript{
		{OS: adminapi.OSMacOS, Name: "macOS", Filename: "connect-gatte.sh", Run: "sh ~/Downloads/connect-gatte.sh"},
		{OS: adminapi.OSLinux, Name: "Linux", Filename: "connect-gatte.sh", Run: "sh ~/Downloads/connect-gatte.sh"},
		{OS: adminapi.OSWindows, Name: "Windows", Filename: "connect-gatte.ps1", Run: `powershell -ExecutionPolicy Bypass -File "$HOME\Downloads\connect-gatte.ps1"`},
	}
}

// Connect is how an analyst connects Claude Code, with the three scripts
// rendered. Not ready, it says which [connect] keys are missing.
func (s *Service) Connect(ctx context.Context, username string) (adminapi.Connect, error) {
	cfg, err := s.config()
	if err != nil {
		return adminapi.Connect{}, err
	}
	info, err := ConnectInfoOf(cfg, username, s.d.Now())
	if err != nil {
		return adminapi.Connect{}, connectErr(err, username)
	}
	out := adminapi.Connect{Ready: info.Ready, Missing: info.MissingKeys}
	if !info.Ready {
		return out, nil
	}
	out.URL, out.ClientID, out.CallbackPort, out.ServerName = info.URL, info.ClientID, info.Port, info.Server
	out.Username, out.HasCA, out.Command = info.Username, info.CAPEM != "", ConnectCommand(info)
	for _, sys := range Systems() {
		text, _, err := RenderScript(info, sys.OS)
		if err != nil {
			return adminapi.Connect{}, adminapi.NewError(adminapi.CodeInternal, "rendering the %s script: %v", sys.Name, err)
		}
		sys.Content = text
		out.Scripts = append(out.Scripts, sys)
	}
	return out, nil
}

// ConnectScript is one script as a file.
func (s *Service) ConnectScript(ctx context.Context, system, username string) (adminapi.ConnectScript, error) {
	c, err := s.Connect(ctx, username)
	if err != nil {
		return adminapi.ConnectScript{}, err
	}
	if !c.Ready {
		return adminapi.ConnectScript{}, adminapi.NewError(adminapi.CodeConnectNotConfigured,
			"connect scripts are not configured: set [connect] %s", strings.Join(c.Missing, " and ")).With("missing", c.Missing)
	}
	for _, sc := range c.Scripts {
		if sc.OS == system {
			return sc, nil
		}
	}
	return adminapi.ConnectScript{}, adminapi.NewError(adminapi.CodeInvalidArgument, "os must be macos, linux or windows").With("field", "os")
}

func connectErr(err error, username string) error {
	if username != "" && strings.HasPrefix(err.Error(), "username") {
		return adminapi.NewError(adminapi.CodeInvalidArgument, "%v", err).With("field", "username")
	}
	return adminapi.NewError(adminapi.CodeConnectNotConfigured, "%v", err)
}

// SuggestUsername turns "Ana Souza" into "ana.souza".
func SuggestUsername(name string) string {
	fold := strings.NewReplacer("á", "a", "à", "a", "â", "a", "ã", "a", "ä", "a", "é", "e", "ê", "e", "è", "e", "í", "i", "î", "i",
		"ó", "o", "ô", "o", "õ", "o", "ö", "o", "ú", "u", "ü", "u", "ç", "c", "ñ", "n")
	var b strings.Builder
	dot := false
	for _, r := range fold.Replace(strings.ToLower(strings.TrimSpace(name))) {
		switch {
		case r < unicode.MaxASCII && (unicode.IsLetter(r) || unicode.IsDigit(r)):
			b.WriteRune(r)
			dot = false
		case (unicode.IsSpace(r) || r == '.' || r == '-' || r == '_') && b.Len() > 0 && !dot:
			b.WriteByte('.')
			dot = true
		}
	}
	out := strings.Trim(b.String(), ".")
	if len(out) > 64 {
		out = out[:64]
	}
	return out
}
