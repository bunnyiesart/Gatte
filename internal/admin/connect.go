// ConnectInfo is what a connect script is made of.
type ConnectInfo struct {
	Ready bool
	// Missing is an English sentence saying what to set, and MissingKeys
	// the [connect] keys it names, when Ready is false.
	Missing     string
	MissingKeys []string
	URL         string
	MetaURL     string
	ClientID    string
	Port        int
	Server      string
	Username    string
	CAPEM       string
	Date        string
}

var safeURLRe = regexp.MustCompile(`^https://[A-Za-z0-9.-]+(:[0-9]{1,5})?(/[A-Za-z0-9._~/-]*)?$`)

// ConnectInfoOf reads what the scripts need from the configuration. Every
// value it returns is safe inside single quotes in sh and PowerShell: the
// URL, names and client id are held to charsets without quotes, and the CA
// is parsed and re-encoded, so it can only be base64 lines.
func ConnectInfoOf(cfg *config.Config, username string, now time.Time) (ConnectInfo, error) {
	c := ConnectInfo{Server: cfg.Connect.ServerName, ClientID: cfg.Connect.ClientID, Port: cfg.Connect.CallbackPort,
		URL: cfg.OIDC.Audience, Date: now.UTC().Format("2006-01-02")}
	if c.Server == "" {
		c.Server = "gatte"
	}
	if c.ClientID == "" {
		c.MissingKeys = []string{"client_id"}
		if c.Port <= 0 {
			c.MissingKeys = append(c.MissingKeys, "callback_port")
		}
		c.Missing = "Set [connect] client_id and callback_port in the configuration file: the public OAuth client your identity provider has registered for Claude Code, and the port of its redirect URI."
		return c, nil
	}
	if !safeURLRe.MatchString(c.URL) {
		return c, fmt.Errorf("oidc.audience %q cannot go into a connect script: it must be a plain https URL", c.URL)
	}
	u, _ := url.Parse(c.URL)
	c.MetaURL = u.Scheme + "://" + u.Host + "/.well-known/oauth-protected-resource"
	if username != "" {
		if err := idp.ValidateAccount(idp.Account{Username: username, DisplayName: "x"}); err != nil {
			return c, err
		}
		c.Username = username
	}
	if cfg.Connect.CAFile != "" {
		pemText, err := canonicalCA(cfg.Connect.CAFile)
		if err != nil {
			return c, err
		}
		c.CAPEM = pemText
	}
	c.Ready = true
	return c, nil
}

// canonicalCA reads a PEM file and returns only its certificates,
// re-encoded: nothing else in the file reaches a script.
func canonicalCA(path string) (string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("connect.ca_file: %w", err)
	}
	var out bytes.Buffer
	for {
		var blk *pem.Block
		blk, b = pem.Decode(b)
		if blk == nil {
			break
		}
		if blk.Type != "CERTIFICATE" {
			continue
		}
		if _, err := x509.ParseCertificate(blk.Bytes); err != nil {
			return "", fmt.Errorf("connect.ca_file: %w", err)
		}
		if err := pem.Encode(&out, &pem.Block{Type: "CERTIFICATE", Bytes: blk.Bytes}); err != nil {
			return "", err
		}
	}
	if out.Len() == 0 {
		return "", errors.New("connect.ca_file: no certificate in it")
	}
	return out.String(), nil
}

var shScript = template.Must(template.New("sh").Parse(`#!/bin/sh
# Connect Claude Code to Gatte, the team's MCP gateway.
{{if .Username}}# For {{.Username}}. {{end}}Generated by mcp-gateway ui on {{.Date}}. Contains no secret.
set -eu

GATTE_URL='{{.URL}}'

say() { printf '%s\n' "$*"; }

if ! command -v claude >/dev/null 2>&1; then
  say "Claude Code isn't installed. Install it, then run this script again:"
  say "  https://docs.claude.com/en/docs/claude-code/setup"
  exit 1
fi
{{if .CAPEM}}
# The gateway's certificate comes from the team's own certificate authority.
GATTE_DIR="$HOME/.config/gatte"
mkdir -p "$GATTE_DIR"
cat > "$GATTE_DIR/ca.pem" <<'GATTE_CA'
{{.CAPEM}}GATTE_CA
export NODE_EXTRA_CA_CERTS="$GATTE_DIR/ca.pem"
added=no
for rc in "$HOME/.zshrc" "$HOME/.bashrc" "$HOME/.profile"; do
  [ -f "$rc" ] || continue
  if ! grep -q 'gatte/ca.pem' "$rc"; then
    printf '\n# Gatte: trust the team certificate authority\nexport NODE_EXTRA_CA_CERTS="$HOME/.config/gatte/ca.pem"\n' >> "$rc"
  fi
  added=yes
done
if [ "$added" = no ]; then
  printf '# Gatte: trust the team certificate authority\nexport NODE_EXTRA_CA_CERTS="$HOME/.config/gatte/ca.pem"\n' >> "$HOME/.profile"
fi
say "✓ Trusted the team certificate authority"
{{end}}
if command -v curl >/dev/null 2>&1; then
  if curl -fsS{{if .CAPEM}} --cacert "$GATTE_DIR/ca.pem"{{end}} -o /dev/null --max-time 10 '{{.MetaURL}}'; then
    say "✓ Gatte answers at $GATTE_URL"
  else
    say "! Gatte didn't answer at $GATTE_URL. Are you on the VPN? Continuing anyway."
  fi
fi

claude mcp remove '{{.Server}}' --scope user >/dev/null 2>&1 || true
claude mcp add --transport http --scope user --client-id '{{.ClientID}}' --callback-port {{.Port}} '{{.Server}}' "$GATTE_URL"

say ""
say "✓ Done. Next: open a new terminal, run claude, type /mcp, choose {{.Server}}{{if .Username}},"
say "  and sign in as {{.Username}}{{end}}."
`))

